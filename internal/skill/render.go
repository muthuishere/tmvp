package skill

import (
	"bytes"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/muthuishere/tmvp/internal/config"
	"github.com/muthuishere/tmvp/internal/errs"
)

// generatedMarker identifies a SKILL.md that tmvp owns (and may rewrite).
const generatedMarker = "<!-- generated by tmvp from config.yaml"

type envRow struct {
	Name        string
	Destructive bool
}

type sysRow struct {
	Name, Type, Labels, Via string
	Envs                    []string
}

// RenderSKILL renders SKILL.md deterministically from cfg. skillDir is the
// path agents pass to --skill.
func RenderSKILL(cfg *config.Config, skillDir string) ([]byte, error) {
	var envs []envRow
	var envNames []string
	idx := map[string]*sysRow{}
	var order []string
	typeSeen := map[string]bool{}
	var types []string
	for _, en := range cfg.EnvOrder {
		e := cfg.Envs[en]
		envs = append(envs, envRow{en, e.Destructive})
		envNames = append(envNames, en)
		for _, sn := range e.SystemOrder {
			s := e.Systems[sn]
			r := idx[sn]
			if r == nil {
				r = &sysRow{Name: sn, Type: s.Type, Labels: labelString(s.Labels), Via: strings.Join(s.Via, " → ")}
				idx[sn] = r
				order = append(order, sn)
			}
			r.Envs = append(r.Envs, en)
			if !typeSeen[s.Type] {
				typeSeen[s.Type] = true
				types = append(types, s.Type)
			}
		}
	}
	sys := make([]sysRow, 0, len(order))
	for _, n := range order {
		sys = append(sys, *idx[n])
	}
	if len(types) == 0 {
		types = []string{"no systems yet"}
	}
	roots := []string{"`assets`"}
	if len(cfg.Assets) > 0 {
		roots = roots[:0]
		for _, a := range cfg.Assets {
			roots = append(roots, "`"+filepath.ToSlash(a)+"`")
		}
	}
	return render("SKILL.md.tmpl", map[string]any{"Product": cfg.Product, "Envs": envs, "EnvNames": envNames,
		"Systems": sys, "Types": types, "SkillDir": filepath.ToSlash(skillDir), "AssetRoots": roots,
		"Refs": references(cfg.Dir)})
}

type refRow struct{ Path, About string }

// references lists <dir>/references/*.md (sorted) with each file's first
// heading or front-matter description, so SKILL.md points agents at them.
func references(dir string) []refRow {
	ms, _ := filepath.Glob(filepath.Join(dir, "references", "*.md"))
	sort.Strings(ms)
	var out []refRow
	for _, m := range ms {
		about := ""
		if b, err := os.ReadFile(m); err == nil {
			for _, ln := range strings.Split(string(b), "\n") {
				ln = strings.TrimSpace(ln)
				if v, ok := strings.CutPrefix(ln, "description:"); ok {
					about = strings.Trim(strings.TrimSpace(v), `"'`)
					break
				}
				if v, ok := strings.CutPrefix(ln, "# "); ok && about == "" {
					about = strings.TrimSpace(v)
				}
			}
		}
		out = append(out, refRow{"references/" + filepath.Base(m), about})
	}
	return out
}

func labelString(m map[string]string) string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	for i, k := range ks {
		ks[i] = k + "=" + m[k]
	}
	return strings.Join(ks, ",")
}

// Sync regenerates SKILL.md next to cfgPath from the config. A SKILL.md
// without the generated marker (hand-written) is left alone.
func Sync(cfgPath string) error {
	cfg, err := config.Load(cfgPath)
	if err != nil {
		return err
	}
	p := filepath.Join(cfg.Dir, "SKILL.md")
	if old, err := os.ReadFile(p); err == nil && !bytes.Contains(old, []byte(generatedMarker)) {
		return errs.New(errs.Usage, "%s is hand-written (no generated marker); not overwriting", p)
	}
	b, err := RenderSKILL(cfg, skillDirArg(cfg.Dir))
	if err != nil {
		return err
	}
	if err := os.WriteFile(p, b, 0o644); err != nil {
		return errs.Wrap(errs.Runtime, err, "write SKILL.md")
	}
	return nil
}

// skillDirArg is the --skill path written into SKILL.md: relative to the
// working directory when the skill is below it (repo-relative), else absolute.
func skillDirArg(dir string) string {
	if wd, err := os.Getwd(); err == nil {
		if rel, err := filepath.Rel(wd, dir); err == nil && !strings.HasPrefix(rel, "..") {
			return rel
		}
	}
	return dir
}
