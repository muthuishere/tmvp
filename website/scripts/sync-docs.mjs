// Copies the repo's agent docs (docs/llms, skills/tmvp-discoverer) into the
// Starlight content tree, and renders the command reference from the CLI's
// own --help, so the site never drifts from the code. Run by `dev`/`build`.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const site = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = dirname(site);
const out = join(site, 'src/content/docs');
const BANNER = '{/* generated by scripts/sync-docs.mjs from the tmvp repo — edit the source, not this file */}';

// llms doc → [section folder, slug, sidebar order]
const map = {
  'overview.md': ['concepts', 'overview', 1],
  'environments.md': ['concepts', 'environments', 2],
  'secrets.md': ['secrets', 'how-it-works', 1],
  'environment-variables.md': ['secrets', 'env-files', 2],
  'secret-managers.md': ['secrets', 'managers', 3],
  'writes.md': ['concepts', 'reads-and-writes', 6],
  'cost-and-timeouts.md': ['concepts', 'limits-cost-timeouts', 7],
  'server.md': ['concepts', 'local-server', 8],
  'logs-and-metrics.md': ['concepts', 'logs-and-metrics', 10],
  'skills.md': ['concepts', 'skills', 11],
  'examples.md': ['start', 'examples', 4],
  'config.md': ['reference', 'config', 2],
  'errors.md': ['reference', 'errors', 3],
  'troubleshooting.md': ['reference', 'troubleshooting', 4],
  'doctor.md': ['reference', 'doctor', 5],
  'install.md': ['reference', 'install-details', 6],
};

// agent-facing docs (llms.txt) that are deliberately not on the website
const llmsOnly = new Set(['why-fast.md']);

const esc = (s) => s.replace(/"/g, '\\"');

// MDX-safe: keep markdown, fix links into the site, escape bare braces/angles outside code.
function convert(md) {
  let title = 'Untitled';
  const lines = md.split('\n');
  const i = lines.findIndex((l) => l.startsWith('# '));
  if (i >= 0) { title = lines[i].slice(2).trim(); lines.splice(i, 1); }
  let body = lines.join('\n')
    .replace(/<!-- BEGIN verbs[^>]*-->\n?/g, '').replace(/<!-- END verbs -->\n?/g, '')
    .replace(/\]\((?:\.\.\/)?(?:docs\/llms\/)?types\/([a-z0-9-]+)\.md\)/g, '](/systems/$1/)')
    .replace(/\]\(([a-z0-9-]+)\.md\)/g, (m, n) => (map[n + '.md'] ? `](/${map[n + '.md'][0]}/${map[n + '.md'][1]}/)` : `](/systems/${n}/)`));
  return { title, body };
}

function write(folder, slug, order, title, body, desc) {
  mkdirSync(join(out, folder), { recursive: true });
  const fm = ['---', `title: "${esc(title)}"`];
  if (desc) fm.push(`description: "${esc(desc)}"`);
  fm.push(`sidebar:\n  order: ${order}`, '---', '');
  // .md keeps braces/angles literal (no MDX parsing of the synced text)
  writeFileSync(join(out, folder, slug + '.md'), fm.join('\n') + '<!-- generated by scripts/sync-docs.mjs — edit the source in the tmvp repo -->\n' + body.trimStart());
}

const llms = join(repo, 'docs/llms');
for (const f of readdirSync(llms).filter((f) => f.endsWith('.md'))) {
  if (llmsOnly.has(f)) continue;
  const m = map[f];
  if (!m) { console.warn('sync-docs: unmapped', f); continue; }
  const { title, body } = convert(readFileSync(join(llms, f), 'utf8'));
  write(m[0], m[1], m[2], title, body);
}

const types = readdirSync(join(llms, 'types')).filter((f) => f.endsWith('.md')).sort();
for (const f of types) {
  const t = basename(f, '.md');
  const { body } = convert(readFileSync(join(llms, 'types', f), 'utf8'));
  const first = body.trim().split('\n')[0];
  write('systems', t, 10, t, body, first.slice(0, 160));
}

// discoverer steps, verbatim
const steps = join(repo, 'skills/tmvp-discoverer/references/steps');
if (existsSync(steps)) {
  let all = '';
  for (const f of readdirSync(steps).filter((f) => f.endsWith('.md')).sort()) {
    const md = readFileSync(join(steps, f), 'utf8');
    all += md.replace(/^# /m, '## ') + '\n';
  }
  write('agent-skills', 'discoverer-steps', 3, 'Discoverer steps (verbatim)', all,
    'The step files the tmvp-discoverer skill follows, copied from the repo.');
  const qb = join(repo, 'skills/tmvp-discoverer/references/questions.md');
  if (existsSync(qb)) {
    const { title, body } = convert(readFileSync(qb, 'utf8'));
    write('agent-skills', 'discoverer-questions', 4, title, body);
  }
}

// command reference from the CLI itself (TMVP_BIN, else go run)
function tmvp(args) {
  const bin = process.env.TMVP_BIN;
  const opts = { cwd: '/', encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, TMVP_NO_SKILL_REFRESH: '1' } };
  return bin ? execFileSync(bin, args, opts) : execFileSync('go', ['run', '-C', repo, './cmd/tmvp', ...args], opts);
}
try {
  const top = tmvp(['help']);
  const cmds = [...top.matchAll(/^  ([a-z][a-z-]+)\s{2,}(.+)$/gm)].map((m) => m[1]).filter((c) => !['help', 'completion'].includes(c));
  let body = 'Rendered from `tmvp help` and `tmvp <command> --help` at build time.\n\n## tmvp\n```text\n' + top.trim() + '\n```\n';
  for (const c of cmds) {
    let h = '';
    try { h = tmvp([c, '--help']); } catch (e) { h = (e.stdout || '') + (e.stderr || ''); }
    h = h.split('\nGlobal Flags:')[0];
    body += `\n## tmvp ${c}\n\`\`\`text\n${h.trim()}\n\`\`\`\n`;
  }
  let verbs = '';
  try { verbs = tmvp(['verbs']); } catch (e) { verbs = e.stdout || ''; }
  if (verbs) body += '\n## Verbs of every type (`tmvp verbs`)\n```text\n' + verbs.trim() + '\n```\n';
  write('reference', 'commands', 1, 'Commands', body, 'Every tmvp command and flag, from the CLI help.');
} catch (e) {
  console.warn('sync-docs: could not run tmvp for the command reference (set TMVP_BIN):', e.message.split('\n')[0]);
}
console.log(`sync-docs: ${Object.keys(map).length} topic docs, ${types.length} system types`);

// the changelog, so the version pill in the header has somewhere to land
const changelog = join(repo, 'CHANGELOG.md');
if (existsSync(changelog)) {
  const { title, body } = convert(readFileSync(changelog, 'utf8'));
  write('reference', 'changelog', 7, title, body, 'What changed in each tmvp release.');
}
